let currentLanguage = 'en';

function setAppLanguage(langKey) {
  if (!I18N_TRANSLATIONS[langKey]) langKey = 'en';
  currentLanguage = langKey;
  const dict = I18N_TRANSLATIONS[langKey];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.innerText = dict[key];
      }
    }
  });

  const langSelect = document.getElementById('globalLanguageSelect');
  if (langSelect && langSelect.value !== langKey) {
    langSelect.value = langKey;
  }
}
